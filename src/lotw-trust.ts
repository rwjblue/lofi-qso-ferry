/** Explicit JSON overrides are supported for private deployments and tests.
 * An empty override deliberately disables trust; it must never enable fallback.
 */
export function lotwTrustRoots(value: string): string[] {
  if (value === "bundled") return [...BUNDLED_LOTW_TRUST_ROOTS];
  let roots: unknown;
  try {
    roots = JSON.parse(value);
  } catch {
    throw new Error("Invalid LoTW trust configuration");
  }
  if (
    !Array.isArray(roots) ||
    roots.length > 8 ||
    roots.some(
      (root) =>
        typeof root !== "string" ||
        root.length > 16_384 ||
        !/^-----BEGIN CERTIFICATE-----\s+[A-Za-z0-9+/=\s]+-----END CERTIFICATE-----\s*$/.test(
          root,
        ),
    )
  )
    throw new Error("Invalid LoTW trust configuration");
  return roots as string[];
}
